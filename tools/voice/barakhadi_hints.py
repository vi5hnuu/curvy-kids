#!/usr/bin/env python3
"""
Turns the barakhadi narration list (generate.txt, one line per syllable, the same text the
recordings speak) into app/src/main/java/.../data/content/BarakhadiHintData.kt.

Each line is one of three shapes, and the screen shows it the way it is spoken:
  "का, का से कान"                 -> Word("कान")          the syllable starts a word
  "खै, ख और ऐ मिलकर बना खै"        -> Joined("ख", "ऐ")      no common word, so how it is built
  "ङ, ङ जैसे गङ्गा में"             -> AsIn("गङ्गा")         the letter only appears inside words

    python3 tools/voice/barakhadi_hints.py [path/to/generate.txt]

Fails on any line that fits none of the shapes, so a typo can't silently drop a syllable.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "generate.txt"
OUT = ROOT / "app/src/main/java/com/vi5hnu/curvykids/data/content/BarakhadiHintData.kt"

WORD = re.compile(r"^(\S+), \1 से (\S+)$")
JOINED = re.compile(r"^(\S+), (\S+) और (\S+) मिलकर बना \1$")
AS_IN = re.compile(r"^(\S+), \1 जैसे (\S+) में$")


def hint(line: str) -> tuple[str, str]:
    if m := WORD.match(line):
        return m[1], f'SyllableHint.Word("{m[2]}")'
    if m := JOINED.match(line):
        return m[1], f'SyllableHint.Joined("{m[2]}", "{m[3]}")'
    if m := AS_IN.match(line):
        return m[1], f'SyllableHint.AsIn("{m[2]}")'
    sys.exit(f"unrecognised line: {line!r}")


def main() -> None:
    lines = [l.strip() for l in SRC.read_text(encoding="utf-8").splitlines() if l.strip()]
    entries = [hint(l) for l in lines]
    body = "\n".join(f'    "{s}" to {h},' for s, h in entries)
    OUT.write_text(f'''package com.vi5hnu.curvykids.data.content

// Generated by tools/voice/barakhadi_hints.py from the barakhadi narration list. Do not edit by
// hand: change the list and re-run the script, so the screen and the recordings stay in step.

/** What each barakhadi syllable's recording says about it, keyed by the syllable. */
internal val BARAKHADI_HINT_DATA: Map<String, SyllableHint> = mapOf(
{body}
)
''', encoding="utf-8")
    print(f"wrote {len(entries)} hints to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
